public class A06_3_Switch {
    public static void main(String[] args) {
        int x = 1;

        switch (x) {
            case 1: {
                int y = 30;
                System.out.println(y);
                break;
            }
            case 2: {
                int y = 30;
                System.out.println(y);
                break;
            }

            case 3: {
                int y = 10;
                System.out.println(y);
                break;
            }
            case 4: {
                int y = 20;
                System.out.println(y);
                break;
            }
        }
    }

}
