public class A10_1_Produktdaten {
    public static void main(String[] args) {

        String Produktname = "Tasse";
        int Stueckzahl = 4;
        float Gewicht = 0.35F;
        long Artikelnummer = 7000000001L;
        boolean Lagerstatus = true;
        char Regalbuchstabe = 'F';

        System.out.println("Produktname: " + Produktname);
        System.out.println("Stueckzahl: " + Stueckzahl);
        System.out.println("Gewicht: " + Gewicht);
        System.out.println("Artikelnummer: " + Artikelnummer);
        System.out.println("Lagerstatus: " + Lagerstatus);
        System.out.println("Regalbuchstabe: " + Regalbuchstabe);

    }
}
