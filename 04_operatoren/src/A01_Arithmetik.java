public class A01_Arithmetik {
    public static void main(String[] args) {

        int erstZahl = 17;
        int zweiteZahl = 5;
        double dritteZahl = 10.0;
        double vierteZahl = 3.0;

        // Addition
        System.out.println("Addition: " + (erstZahl + zweiteZahl));

        // Subtraktion
        System.out.println("Subtraktion: " + (erstZahl - zweiteZahl));

        // Multiplikation
        System.out.println("Multiplikation: " + (erstZahl * zweiteZahl));

        // Division
        System.out.println("Division: " + (erstZahl / zweiteZahl));

        // Modulu
        System.out.println("rest: " + (erstZahl % zweiteZahl));

        System.out.println("dri & vie: " + dritteZahl + " " + vierteZahl);
    }

}
