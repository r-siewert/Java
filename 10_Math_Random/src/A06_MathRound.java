public class A06_MathRound {
    public static void main(String[] args) {
        
        double round1 = 7.8;
        System.out.println("Aufgerundet: " + Math.round(round1));


        double wert2 = 7.4;
        System.out.println("Abgerundet: " + Math.round(wert2));

        double wert3 = 7.5;
        System.out.println("Abgerundet: " + Math.round(wert3));

        // Round rundet ab .5 automatisch auf und drunter natürlich ab!
    }
    
}
