public class A01_Variablen {
    public static void main(String[] args) {

        int alter = 39;

        double koerpergroesse = 1.86;

        int hausnummer;
        hausnummer = 12;

        boolean javaMachtSpass = true;

        char kursBuchstabe = 'A';

        String name = "Reinhard";

        System.out.println("Name: " + name);

        System.out.println("Hausnummer: " + hausnummer);

        System.out.println("Koerpergroesse: " + koerpergroesse);

        System.out.println("Java ist toll: " + javaMachtSpass);

        System.out.println("Buchstabe des Kurses: " + kursBuchstabe);

        System.out.println("Mein Alter ist: " + alter);
    }
}
