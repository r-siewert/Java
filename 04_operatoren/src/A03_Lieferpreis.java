public class A03_Lieferpreis {
    public static void main(String[] args) {

        int rechnung1 = 6 + 4 * 3; // 4 * 3 = 12 + 6 = 18
        int rechnung2 = (6 + 4) * 3; // 6 + 4 = 10 * 3 = 30

        System.out.println("Standard: " + rechnung1);
        System.out.println("Mit Zuschlag: " + rechnung2);

    }
}
